/// Marks a file as ours, so a later run may replace it and nothing else is.
pub const MARKER: &str = "<!-- generated by multiagent-chat";

/// The documents task 0013 requires, in the order they are written.
pub const DOCUMENTS: [&str; 6] = [
    "README.md",
    "docs/ARCHITECTURE.md",
    "docs/DEVELOPMENT_LOG.md",
    "docs/DECISIONS.md",
    "docs/AI_USAGE.md",
    "docs/NEXT_STEPS.md",
];

/// What one generation produced. Paths are project-relative, never absolute:
/// an internal workspace path must not reach an event, a report or a document.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Submission {
    /// Documents written, in project-relative form.
    pub written: Vec<String>,
    /// Existing documents left exactly as they were.
    pub preserved: Vec<String>,
    /// Exact identities of the files this run wrote, including fallback
    /// `*.generated.md` destinations selected to preserve hand-written docs.
    pub artifacts: Vec<GeneratedArtifact>,
}

/// Everything the documents are rendered from.
pub struct SubmissionInputs<'a> {
    /// A REDACTED task snapshot; see `TaskManager::evidence_snapshot`.
    pub task: &'a Task,
    pub profile: &'a ProjectProfile,
    /// Every verification command this run actually executed.
    pub verification: &'a [VerificationResult],
    /// The finished project, inspected only for which files exist.
    pub project: &'a Path,
}

/// Render all six documents. Pure: it reads task state and file existence only.
pub fn documents(inputs: &SubmissionInputs<'_>) -> Vec<(&'static str, String)> {
    let rendered = vec![
        ("README.md", readme(inputs)),
        ("docs/ARCHITECTURE.md", architecture(inputs)),
        (
            "docs/DEVELOPMENT_LOG.md",
            header(inputs.task) + &crate::evidence::development_log(inputs.task),
        ),
        (
            "docs/DECISIONS.md",
            header(inputs.task) + &crate::evidence::decisions(inputs.task),
        ),
        (
            "docs/AI_USAGE.md",
            header(inputs.task) + &crate::evidence::agent_usage(inputs.task),
        ),
        ("docs/NEXT_STEPS.md", next_steps(inputs)),
    ];
    debug_assert_eq!(
        rendered.iter().map(|(name, _)| *name).collect::<Vec<_>>(),
        DOCUMENTS,
        "every required document must be rendered, in order"
    );
    rendered
}

/// Write the complete document set into the finished project.
///
/// Every destination is resolved and every document is staged before an
/// existing project file is changed. Finalization rolls back any replacement if
/// a later rename fails, so a failed generation never looks like a successful,
/// partial six-file submission. Hand-written documentation is only observed,
/// never opened for writing.
pub fn write_into(project: &Path, documents: &[(&'static str, String)]) -> Result<Submission> {
    write_into_with(project, documents, |_, path, contents| {
        fs::write(path, contents)
    })
}

struct PlannedDocument {
    name: &'static str,
    destination: PathBuf,
    preserved: Option<String>,
}

struct StagingDirectory {
    path: PathBuf,
}

impl Drop for StagingDirectory {
    fn drop(&mut self) {
        // This directory was created exclusively by this operation inside the
        // project, and is only ever an unpublished staging area.
        let _ = fs::remove_dir_all(&self.path);
    }
}

fn write_into_with<F>(
    project: &Path,
    documents: &[(&'static str, String)],
    mut stage_write: F,
) -> Result<Submission>
where
    F: FnMut(&str, &Path, &str) -> std::io::Result<()>,
{
    let planned = plan_documents(project, documents)?;
    let stage = create_staging_directory(project)?;
    let mut staged = Vec::with_capacity(planned.len());
    for (index, (document, contents)) in documents.iter().enumerate() {
        let path = stage.path.join(format!("document-{index}.md"));
        stage_write(document, &path, contents)
            .with_context(|| format!("could not stage generated documentation {document}"))?;
        staged.push(path);
    }
    finalize_documents(project, &planned, &staged, documents)
}

fn plan_documents(
    project: &Path,
    documents: &[(&'static str, String)],
) -> Result<Vec<PlannedDocument>> {
    if documents.len() != DOCUMENTS.len() || documents.iter().map(|(name, _)| *name).ne(DOCUMENTS) {
        bail!("the complete required documentation set was not rendered");
    }
    documents
        .iter()
        .map(|(name, _)| {
            let target = project.join(name);
            let (destination, preserved) = destination(&target, name)?;
            if let Ok(metadata) = fs::symlink_metadata(&destination)
                && (crate::repository_file::is_link(&metadata)
                    || !metadata.is_file()
                    || !fs::read_to_string(&destination)
                        .is_ok_and(|contents| contents.starts_with(MARKER)))
            {
                bail!("refusing to replace a linked, non-regular, or hand-written generated documentation file");
            }
            Ok(PlannedDocument {
                name,
                destination,
                preserved,
            })
        })
        .collect()
}

fn create_staging_directory(project: &Path) -> Result<StagingDirectory> {
    let path = project.join(format!(".multiagent-chat-docs-{}", uuid::Uuid::new_v4()));
    fs::create_dir(&path).context("could not create documentation staging directory")?;
    Ok(StagingDirectory { path })
}

fn finalize_documents(
    project: &Path,
    planned: &[PlannedDocument],
    staged: &[PathBuf],
    documents: &[(&'static str, String)],
) -> Result<Submission> {
    let mut finalized: Vec<(PathBuf, Option<PathBuf>)> = Vec::with_capacity(planned.len());
    for (index, (plan, staged)) in planned.iter().zip(staged).enumerate() {
        if let Some(parent) = plan.destination.parent()
            && let Err(error) = fs::create_dir_all(parent)
        {
            rollback_documents(&finalized);
            return Err(error).with_context(|| {
                format!(
                    "could not create the documentation folder for {}",
                    plan.name
                )
            });
        }
        let backup = if plan.destination.exists() {
            let backup = staged.with_file_name(format!("backup-{index}.md"));
            if let Err(error) = fs::rename(&plan.destination, &backup) {
                rollback_documents(&finalized);
                return Err(error).with_context(|| {
                    format!(
                        "could not prepare generated documentation {} for replacement",
                        plan.name
                    )
                });
            }
            Some(backup)
        } else {
            None
        };
        if let Err(error) = fs::rename(staged, &plan.destination) {
            if let Some(backup) = &backup {
                let _ = fs::rename(backup, &plan.destination);
            }
            rollback_documents(&finalized);
            return Err(error).with_context(|| {
                format!("could not finalize generated documentation {}", plan.name)
            });
        }
        finalized.push((plan.destination.clone(), backup));
    }
    Ok(Submission {
        written: planned
            .iter()
            .map(|plan| relative(project, &plan.destination))
            .collect(),
        preserved: planned
            .iter()
            .filter_map(|plan| plan.preserved.clone())
            .collect(),
        artifacts: planned
            .iter()
            .zip(documents)
            .map(|(plan, (_, contents))| GeneratedArtifact {
                path: relative(project, &plan.destination),
                content_sha256: sha256(contents.as_bytes()),
            })
            .collect(),
    })
}

fn sha256(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

fn rollback_documents(finalized: &[(PathBuf, Option<PathBuf>)]) {
    for (destination, backup) in finalized.iter().rev() {
        let _ = fs::remove_file(destination);
        if let Some(backup) = backup {
            let _ = fs::rename(backup, destination);
        }
    }
}

/// Where a document may go, and what was preserved to keep it safe.
fn destination(target: &Path, name: &str) -> Result<(PathBuf, Option<String>)> {
    match fs::symlink_metadata(target) {
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok((target.into(), None)),
        Err(error) => Err(error).with_context(|| format!("could not inspect {name}")),
        Ok(metadata) => {
            // A link is never followed and never replaced.
            if !crate::repository_file::is_link(&metadata)
                && metadata.is_file()
                && fs::read_to_string(target).is_ok_and(|existing| existing.starts_with(MARKER))
            {
                // Ours from an earlier run: replacing it destroys nothing.
                return Ok((target.into(), None));
            }
            let stem = target
                .file_stem()
                .and_then(|stem| stem.to_str())
                .ok_or_else(|| anyhow::anyhow!("unsupported documentation name {name}"))?;
            Ok((
                target.with_file_name(format!("{stem}.generated.md")),
                Some(name.to_string()),
            ))
        }
    }
}

fn relative(project: &Path, path: &Path) -> String {
    path.strip_prefix(project)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

