fn header(task: &Task) -> String {
    format!(
        "{MARKER} for task {} — regenerate rather than editing in place -->\n\n",
        task.id
    )
}

fn readme(inputs: &SubmissionInputs<'_>) -> String {
    let task = inputs.task;
    let mut markdown = header(task);
    markdown.push_str(&format!("# {}\n\n", one_line(&task.title)));
    markdown.push_str("## Purpose\n\n");
    markdown.push_str(&quote(&task.description));
    markdown.push_str("\n\n## Architecture summary\n\n");
    markdown.push_str(&match spec_section(task, "Architecture") {
        Some(section) => summarize(&section),
        None => "The approved specification recorded no architecture section.".into(),
    });
    markdown.push_str("\n\n## Prerequisites\n\n");
    for prerequisite in prerequisites(inputs.profile) {
        markdown.push_str(&format!("- {prerequisite}\n"));
    }
    markdown.push_str(
        "\n## Running it locally\n\n\
         This project was built and checked in an isolated workspace. Only the commands \
         listed under **Verified commands** were executed there; no other start, build or \
         deployment command has been verified by this run.\n\n",
    );
    startup_section(&mut markdown, inputs);

    let configuration = present_files(inputs.project, &[".env.example", ".env.sample", ".env"]);
    markdown.push_str("## Configuration\n\n");
    if configuration.is_empty() {
        markdown.push_str("No configuration template was detected in the project.\n\n");
    } else {
        markdown.push_str("The project defines:\n\n");
        for file in &configuration {
            markdown.push_str(&format!("- `{file}`\n"));
        }
        markdown.push('\n');
    }

    let migrations = present_files(
        inputs.project,
        &[
            "migrations",
            "db/migrate",
            "alembic.ini",
            "prisma/schema.prisma",
        ],
    );
    if !migrations.is_empty() {
        markdown.push_str("## Database setup\n\n");
        markdown.push_str("The project defines database assets:\n\n");
        for file in &migrations {
            markdown.push_str(&format!("- `{file}`\n"));
        }
        markdown.push_str("\nNo migration command was executed by this run.\n\n");
    }

    let containers = present_files(
        inputs.project,
        &[
            "Dockerfile",
            "docker-compose.yml",
            "docker-compose.yaml",
            "compose.yaml",
        ],
    );
    if !containers.is_empty() {
        markdown.push_str("## Containers\n\n");
        for file in &containers {
            markdown.push_str(&format!("- `{file}`\n"));
        }
        markdown.push_str("\nNo container build or start command was executed by this run.\n\n");
    }

    markdown.push_str("## Verified commands\n\n");
    if inputs.verification.is_empty() {
        markdown.push_str(
            "This run detected no automatic verification command for the project, so no build \
             or test command is claimed to work here.\n\n",
        );
    } else {
        markdown.push_str("| Command | Result |\n| --- | --- |\n");
        for result in inputs.verification {
            markdown.push_str(&format!(
                "| `{}` | {} |\n",
                one_line(&result.command),
                if result.success { "passed" } else { "FAILED" }
            ));
        }
        markdown.push('\n');
    }

    markdown.push_str("## Current status\n\n");
    markdown.push_str(&status_lines(task));
    markdown.push_str("\n## Known limitations\n\n");
    let limitations = limitations(task);
    if limitations.is_empty() {
        markdown.push_str("No limitation was recorded by this run.\n");
    } else {
        for limitation in limitations {
            markdown.push_str(&format!("- {limitation}\n"));
        }
    }
    markdown
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct StartupCommand {
    scope: &'static str,
    command: String,
    detected_from: &'static str,
}

/// Startup commands supported by project metadata. These are documentation
/// hints only: they are never merged into verification results.
fn startup_commands(inputs: &SubmissionInputs<'_>) -> Vec<StartupCommand> {
    let root = inputs.project;
    let mut commands = Vec::new();
    if root.join("Cargo.toml").is_file() && root.join("src/main.rs").is_file() {
        commands.push(StartupCommand {
            scope: "Local application",
            command: "cargo run".into(),
            detected_from: "Cargo.toml and src/main.rs",
        });
    }
    if root.join("pom.xml").is_file()
        && project_text(root, "pom.xml")
            .is_some_and(|pom| pom.to_ascii_lowercase().contains("spring-boot"))
    {
        commands.push(StartupCommand {
            scope: "Backend",
            command: if root.join("mvnw").is_file() {
                "./mvnw spring-boot:run"
            } else {
                "mvn spring-boot:run"
            }
            .into(),
            detected_from: "pom.xml",
        });
    }
    let gradle = ["build.gradle.kts", "build.gradle"]
        .into_iter()
        .find(|name| root.join(name).is_file());
    if let Some(gradle) = gradle
        && project_text(root, gradle)
            .is_some_and(|build| build.to_ascii_lowercase().contains("spring-boot"))
    {
        commands.push(StartupCommand {
            scope: "Backend",
            command: if root.join("gradlew").is_file() {
                "./gradlew bootRun"
            } else {
                "gradle bootRun"
            }
            .into(),
            detected_from: gradle,
        });
    }
    if let Some(scripts) = project_scripts(root) {
        for (scope, names) in [
            ("Local development", &["dev", "start"][..]),
            (
                "Backend",
                &["dev:backend", "start:backend", "backend", "server", "api"][..],
            ),
            (
                "Frontend",
                &["dev:frontend", "start:frontend", "frontend", "client"][..],
            ),
        ] {
            for name in names {
                if scripts.contains(*name) {
                    commands.push(StartupCommand {
                        scope,
                        command: if *name == "start" {
                            "npm start".into()
                        } else {
                            format!("npm run {name}")
                        },
                        detected_from: "package.json",
                    });
                }
            }
        }
    }
    if root.join("manage.py").is_file() {
        commands.push(StartupCommand {
            scope: "Backend",
            command: "python manage.py runserver".into(),
            detected_from: "manage.py",
        });
    }
    if let Some(compose) = ["docker-compose.yml", "docker-compose.yaml", "compose.yaml"]
        .into_iter()
        .find(|name| root.join(name).is_file())
    {
        commands.push(StartupCommand {
            scope: "Containers",
            command: format!("docker compose -f {compose} up"),
            detected_from: compose,
        });
    }
    commands
}

fn startup_section(markdown: &mut String, inputs: &SubmissionInputs<'_>) {
    markdown.push_str("## Detected startup commands (not executed)\n\n");
    let commands = startup_commands(inputs);
    if commands.is_empty() {
        markdown.push_str("No deterministic startup command was detected from project files.\n\n");
        return;
    }
    markdown.push_str(
        "These commands were derived from project files and were **not executed or verified** by this run.\n\n\
         | Scope | Command | Detected from |\n| --- | --- | --- |\n",
    );
    for command in commands {
        markdown.push_str(&format!(
            "| {} | `{}` | `{}` |\n",
            command.scope, command.command, command.detected_from
        ));
    }
    markdown.push('\n');
}

fn project_scripts(root: &Path) -> Option<std::collections::BTreeSet<String>> {
    let text = project_text(root, "package.json")?;
    serde_json::from_str::<serde_json::Value>(&text)
        .ok()?
        .get("scripts")?
        .as_object()
        .map(|scripts| scripts.keys().cloned().collect())
}

fn project_text(root: &Path, name: &str) -> Option<String> {
    let path = root.join(name);
    let mut text = String::new();
    crate::repository_file::open(root, &path)
        .ok()?
        .take(64 * 1024)
        .read_to_string(&mut text)
        .ok()?;
    Some(text)
}

fn architecture(inputs: &SubmissionInputs<'_>) -> String {
    let task = inputs.task;
    let mut markdown = header(task);
    markdown.push_str("# Architecture\n\n## Technology\n\n");
    markdown.push_str(&format!("- Stack: {}\n", stack_name(&inputs.profile.stack)));
    markdown.push_str(&format!(
        "- Build tool: {}\n",
        build_tool_name(&inputs.profile.build_tool)
    ));
    if let Some(framework) = &inputs.profile.framework {
        markdown.push_str(&format!("- Framework: {}\n", one_line(framework)));
    }
    if !inputs.profile.evidence.is_empty() {
        markdown.push_str(&format!(
            "- Detected from: {}\n",
            inputs
                .profile
                .evidence
                .iter()
                .map(|evidence| format!("`{}`", one_line(evidence)))
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }

    for (heading, section) in [
        ("Approved architecture", "Architecture"),
        ("Agreed solution", "Agreed solution"),
    ] {
        markdown.push_str(&format!("\n## {heading}\n\n"));
        markdown.push_str(&match spec_section(task, section) {
            Some(body) => body,
            None => format!("The approved specification recorded no {section} section."),
        });
        markdown.push('\n');
    }

    markdown.push_str("\n## Implemented components\n\n");
    if task.milestones.is_empty() {
        markdown.push_str("No milestone plan was recorded.\n");
    } else {
        for milestone in &task.milestones {
            markdown.push_str(&format!(
                "- **{}. {}** — {} ({})\n",
                milestone.order,
                one_line(&milestone.title),
                one_line(&milestone.objective),
                milestone.status.label()
            ));
            if let Some(commit) = &milestone.commit {
                markdown.push_str(&format!("  - Commit `{}`\n", one_line(&commit.short_sha)));
            }
            if !milestone.criteria.is_empty() {
                markdown.push_str(&format!(
                    "  - Acceptance criteria: {}\n",
                    milestone.criteria.join(", ")
                ));
            }
        }
    }

    markdown.push_str("\n## Recorded risks and constraints\n\n");
    markdown.push_str(&match spec_section(task, "Open risks") {
        Some(body) => body,
        None => "The approved specification recorded no open risks.".into(),
    });
    markdown.push('\n');
    markdown
}

fn next_steps(inputs: &SubmissionInputs<'_>) -> String {
    let task = inputs.task;
    let mut markdown = header(task);
    markdown.push_str("# Next steps\n\n## Required but incomplete\n\n");

    let outstanding = task
        .acceptance
        .iter()
        .filter(|criterion| criterion.status.is_outstanding())
        .collect::<Vec<_>>();
    let mut required = Vec::new();
    for criterion in &outstanding {
        required.push(format!(
            "`{}` [{}] {}{}",
            criterion.id,
            criterion.status.label(),
            one_line(&criterion.description),
            if criterion.milestones.is_empty() {
                " (no milestone in this run was responsible for it)".to_string()
            } else {
                String::new()
            }
        ));
        for finding in &criterion.blocking_findings {
            required.push(format!("  - Unresolved finding: {}", one_line(finding)));
        }
    }
    for milestone in &task.milestones {
        if let Some(review) = &milestone.review
            && !review.status.is_pass()
        {
            required.push(format!(
                "Milestone {} did not pass implementation review ({})",
                milestone.order,
                review.summary()
            ));
        }
    }
    for result in inputs.verification.iter().filter(|result| !result.success) {
        required.push(format!(
            "Verification command `{}` failed",
            one_line(&result.command)
        ));
    }
    if required.is_empty() {
        markdown.push_str("Nothing required by the approved specification is outstanding.\n");
    } else {
        for item in required {
            markdown.push_str(&format!("- {item}\n"));
        }
    }

    markdown.push_str("\n## Deferred work\n\n");
    let deferred = task
        .acceptance
        .iter()
        .filter(|criterion| criterion.status == CriterionStatus::Deferred)
        .collect::<Vec<_>>();
    if deferred.is_empty() {
        markdown.push_str("No requirement was deferred.\n");
    } else {
        for criterion in deferred {
            markdown.push_str(&format!(
                "- `{}` {}\n",
                criterion.id,
                one_line(&criterion.description)
            ));
        }
    }

    markdown.push_str("\n## Optional future improvements\n\n");
    markdown.push_str(
        "Recorded by the approved specification as out of scope; none of it was implemented \
         or verified by this run.\n\n",
    );
    markdown.push_str(&match spec_section(task, "Out of scope") {
        Some(body) => body,
        None => "The approved specification recorded nothing as out of scope.".into(),
    });
    markdown.push('\n');
    markdown
}

