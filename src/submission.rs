/// Marks a file as ours, so a later run may replace it and nothing else is.
pub const MARKER: &str = "<!-- generated by multiagent-chat";

/// The documents task 0013 requires, in the order they are written.
pub const DOCUMENTS: [&str; 6] = [
    "README.md",
    "docs/ARCHITECTURE.md",
    "docs/DEVELOPMENT_LOG.md",
    "docs/DECISIONS.md",
    "docs/AI_USAGE.md",
    "docs/NEXT_STEPS.md",
];

/// What one generation produced. Paths are project-relative, never absolute:
/// an internal workspace path must not reach an event, a report or a document.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Submission {
    /// Documents written, in project-relative form.
    pub written: Vec<String>,
    /// Existing documents left exactly as they were.
    pub preserved: Vec<String>,
}

/// Everything the documents are rendered from.
pub struct SubmissionInputs<'a> {
    /// A REDACTED task snapshot; see `TaskManager::evidence_snapshot`.
    pub task: &'a Task,
    pub profile: &'a ProjectProfile,
    /// Every verification command this run actually executed.
    pub verification: &'a [VerificationResult],
    /// The finished project, inspected only for which files exist.
    pub project: &'a Path,
}

/// Render all six documents. Pure: it reads task state and file existence only.
pub fn documents(inputs: &SubmissionInputs<'_>) -> Vec<(&'static str, String)> {
    let rendered = vec![
        ("README.md", readme(inputs)),
        ("docs/ARCHITECTURE.md", architecture(inputs)),
        (
            "docs/DEVELOPMENT_LOG.md",
            header(inputs.task) + &crate::evidence::development_log(inputs.task),
        ),
        (
            "docs/DECISIONS.md",
            header(inputs.task) + &crate::evidence::decisions(inputs.task),
        ),
        (
            "docs/AI_USAGE.md",
            header(inputs.task) + &crate::evidence::agent_usage(inputs.task),
        ),
        ("docs/NEXT_STEPS.md", next_steps(inputs)),
    ];
    debug_assert_eq!(
        rendered.iter().map(|(name, _)| *name).collect::<Vec<_>>(),
        DOCUMENTS,
        "every required document must be rendered, in order"
    );
    rendered
}

/// Write the documents into the finished project.
///
/// A path that already holds a file this run did not generate is preserved and
/// the document goes to `<name>.generated.md` beside it, so existing
/// documentation is never destroyed and nothing is silently dropped.
pub fn write_into(project: &Path, documents: &[(&'static str, String)]) -> Result<Submission> {
    let mut submission = Submission::default();
    for (name, contents) in documents {
        let target = project.join(name);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("could not create the documentation folder for {name}"))?;
        }
        let (path, preserved) = destination(&target, name)?;
        write_document(&path, contents)
            .with_context(|| format!("could not write generated documentation {name}"))?;
        if let Some(preserved) = preserved {
            submission.preserved.push(preserved);
        }
        submission.written.push(relative(project, &path));
    }
    Ok(submission)
}

/// Where a document may go, and what was preserved to keep it safe.
fn destination(target: &Path, name: &str) -> Result<(PathBuf, Option<String>)> {
    match fs::symlink_metadata(target) {
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok((target.into(), None)),
        Err(error) => Err(error).with_context(|| format!("could not inspect {name}")),
        Ok(metadata) => {
            // A link is never followed and never replaced.
            if !crate::repository_file::is_link(&metadata)
                && metadata.is_file()
                && fs::read_to_string(target).is_ok_and(|existing| existing.starts_with(MARKER))
            {
                // Ours from an earlier run: replacing it destroys nothing.
                return Ok((target.into(), None));
            }
            let stem = target
                .file_stem()
                .and_then(|stem| stem.to_str())
                .ok_or_else(|| anyhow::anyhow!("unsupported documentation name {name}"))?;
            Ok((
                target.with_file_name(format!("{stem}.generated.md")),
                Some(name.to_string()),
            ))
        }
    }
}

/// Replace by rename, so an existing directory entry is never opened.
fn write_document(path: &Path, contents: &str) -> Result<()> {
    if let Ok(metadata) = fs::symlink_metadata(path)
        && (crate::repository_file::is_link(&metadata) || !metadata.is_file())
    {
        bail!("refusing to replace a linked or non-regular documentation file");
    }
    let parent = path
        .parent()
        .ok_or_else(|| anyhow::anyhow!("documentation path has no parent"))?;
    let temporary = parent.join(format!(".docs-{}.tmp", uuid::Uuid::new_v4()));
    let result = fs::write(&temporary, contents).and_then(|()| fs::rename(&temporary, path));
    if result.is_err() {
        let _ = fs::remove_file(&temporary);
    }
    Ok(result?)
}

fn relative(project: &Path, path: &Path) -> String {
    path.strip_prefix(project)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

