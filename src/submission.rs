    /// Required test 7: the development log uses the recorded timestamps.
    #[test]
    fn the_development_log_uses_recorded_timestamps() {
        let root = project("timestamps");
        let task = finished_task("unused-secret-value");
        let recorded = task
            .history
            .iter()
            .map(|event| {
                event
                    .timestamp
                    .to_rfc3339_opts(chrono::SecondsFormat::Millis, true)
            })
            .collect::<Vec<_>>();

        generate(&task, &root, &verification());

        let log = read(&root, "docs/DEVELOPMENT_LOG.md");
        for timestamp in &recorded {
            assert!(log.contains(timestamp), "{timestamp} missing from the log");
        }
        assert!(log.contains("Sequence: 1"), "{log}");
        // Nothing invents a time of its own.
        let stamps = log.matches("T").count();
        assert!(stamps >= recorded.len(), "{log}");
        fs::remove_dir_all(root).ok();
    }

