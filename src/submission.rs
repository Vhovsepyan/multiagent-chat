/// Which of these project-relative paths exist, so a document mentions only
/// what the finished project really contains.
fn present_files(project: &Path, candidates: &[&str]) -> Vec<String> {
    candidates
        .iter()
        .filter(|candidate| {
            fs::symlink_metadata(project.join(candidate))
                .is_ok_and(|metadata| !crate::repository_file::is_link(&metadata))
        })
        .map(|candidate| (*candidate).to_string())
        .collect()
}

fn one_line(value: &str) -> String {
    value.replace(['\r', '\n'], " ").trim().to_string()
}

fn quote(value: &str) -> String {
    let value = value.trim();
    if value.is_empty() {
        "No description was recorded.".to_string()
    } else {
        value.to_string()
    }
}

/// The audit line for a completed generation.
pub fn generated_event(submission: &Submission) -> TaskEvent {
    TaskEvent::SubmissionDocumentationGenerated {
        written: submission.written.clone(),
        preserved: submission.preserved.clone(),
        artifacts: submission.artifacts.clone(),
    }
}

