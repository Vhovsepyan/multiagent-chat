    /// Required test 5: documentation the run did not write is never destroyed.
    #[test]
    fn existing_documentation_is_preserved() {
        let root = project("preserve");
        let task = finished_task("unused-secret-value");
        fs::create_dir_all(root.join("docs")).unwrap();
        fs::write(root.join("README.md"), "# Hand-written\n\nKeep me.\n").unwrap();
        fs::write(
            root.join("docs/ARCHITECTURE.md"),
            "# Hand-written architecture\n",
        )
        .unwrap();

        let submission = generate(&task, &root, &verification());

        assert_eq!(
            fs::read_to_string(root.join("README.md")).unwrap(),
            "# Hand-written\n\nKeep me.\n",
            "an existing README is never overwritten"
        );
        assert_eq!(
            fs::read_to_string(root.join("docs/ARCHITECTURE.md")).unwrap(),
            "# Hand-written architecture\n"
        );
        assert_eq!(
            submission.preserved,
            vec!["README.md".to_string(), "docs/ARCHITECTURE.md".to_string()]
        );
        assert!(
            submission
                .written
                .contains(&"README.generated.md".to_string())
        );
        assert!(
            submission
                .written
                .contains(&"docs/ARCHITECTURE.generated.md".to_string())
        );
        assert!(read(&root, "README.generated.md").contains("# Event service"));

        // A second run replaces only what the first run generated.
        let submission = generate(&task, &root, &verification());
        assert_eq!(submission.preserved.len(), 2);
        assert_eq!(
            fs::read_to_string(root.join("README.md")).unwrap(),
            "# Hand-written\n\nKeep me.\n"
        );
        assert!(read(&root, "docs/NEXT_STEPS.md").starts_with(MARKER));
        fs::remove_dir_all(root).ok();
    }

