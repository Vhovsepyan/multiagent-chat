/// The run's own status, stated plainly enough that an incomplete task cannot
/// read as a finished one.
fn status_lines(task: &Task) -> String {
    let passed = task
        .acceptance
        .iter()
        .filter(|criterion| criterion.status == CriterionStatus::Passed)
        .count();
    let mut lines = format!(
        "- Task status: **{}**\n",
        match task.status {
            TaskStatus::Completed => "completed",
            TaskStatus::Failed => "failed",
            TaskStatus::Cancelled => "cancelled",
            TaskStatus::Rejected => "rejected",
            _ => "in progress",
        }
    );
    if task.acceptance.is_empty() {
        lines.push_str("- No acceptance criteria were generated for this run.\n");
    } else {
        lines.push_str(&format!(
            "- Acceptance criteria: **{passed} of {} passed**\n",
            task.acceptance.len()
        ));
        let outstanding = task
            .acceptance
            .iter()
            .filter(|criterion| criterion.status.is_outstanding())
            .map(|criterion| criterion.id.as_str())
            .collect::<Vec<_>>();
        if !outstanding.is_empty() {
            lines.push_str(&format!(
                "- Outstanding criteria: {} — see `docs/NEXT_STEPS.md`\n",
                outstanding.join(", ")
            ));
        }
    }
    if let Some(error) = &task.error {
        lines.push_str(&format!("- Recorded error: {}\n", one_line(error)));
    }
    if task.status != TaskStatus::Completed
        || task
            .acceptance
            .iter()
            .any(|criterion| criterion.status.is_outstanding())
    {
        lines.push_str(
            "- This project is **not** complete: the items above were not satisfied by this run.\n",
        );
    }
    lines
}

fn limitations(task: &Task) -> Vec<String> {
    let mut limitations = Vec::new();
    for criterion in &task.acceptance {
        if criterion.status.is_outstanding() {
            limitations.push(format!(
                "`{}` is {} — {}",
                criterion.id,
                criterion.status.label(),
                one_line(&criterion.description)
            ));
        }
    }
    for milestone in &task.milestones {
        if let Some(review) = &milestone.review {
            for finding in &review.findings {
                limitations.push(format!(
                    "Unresolved review finding: {}",
                    one_line(&finding.requirement)
                ));
            }
        }
    }
    if let Some(error) = &task.error {
        limitations.push(one_line(error));
    }
    limitations
}

/// The approved specification's own words for one section.
fn spec_section(task: &Task, name: &str) -> Option<String> {
    let specification = task.spec.as_deref()?;
    let body = crate::evidence::markdown_section(specification, name)?;
    (!body.trim().is_empty()).then(|| body.trim().to_string())
}

/// The first paragraph, which is enough for a summary.
fn summarize(section: &str) -> String {
    section
        .split("\n\n")
        .next()
        .unwrap_or(section)
        .trim()
        .to_string()
}

fn prerequisites(profile: &ProjectProfile) -> Vec<String> {
    let mut prerequisites = match profile.stack {
        TechStack::Rust => vec!["A stable Rust toolchain (`cargo`)".to_string()],
        TechStack::JavaSpringBoot => vec!["A JDK".to_string()],
        TechStack::Python => vec!["A Python 3 interpreter".to_string()],
        TechStack::TypeScriptNode => vec!["Node.js and npm".to_string()],
        TechStack::Custom => vec![
            "The toolchain this project's build files require; none was detected automatically"
                .to_string(),
        ],
    };
    match profile.build_tool {
        BuildTool::Maven => prerequisites.push("Maven, or the repository's `mvnw` wrapper".into()),
        BuildTool::Gradle => {
            prerequisites.push("Gradle, or the repository's `gradlew` wrapper".into())
        }
        _ => {}
    }
    prerequisites.push("Git".into());
    prerequisites
}

fn stack_name(stack: &TechStack) -> &'static str {
    match stack {
        TechStack::Rust => "Rust",
        TechStack::JavaSpringBoot => "Java / Spring Boot",
        TechStack::Python => "Python",
        TechStack::TypeScriptNode => "TypeScript / Node.js",
        TechStack::Custom => "Custom / other",
    }
}

fn build_tool_name(tool: &BuildTool) -> &'static str {
    match tool {
        BuildTool::Cargo => "Cargo",
        BuildTool::Maven => "Maven",
        BuildTool::Gradle => "Gradle",
        BuildTool::Npm => "npm",
        BuildTool::Python => "Python tooling",
        BuildTool::Custom => "not detected",
    }
}

/// Which of these project-relative paths exist, so a document mentions only
/// what the finished project really contains.
fn present_files(project: &Path, candidates: &[&str]) -> Vec<String> {
    candidates
        .iter()
        .filter(|candidate| {
            fs::symlink_metadata(project.join(candidate))
                .is_ok_and(|metadata| !crate::repository_file::is_link(&metadata))
        })
        .map(|candidate| (*candidate).to_string())
        .collect()
}

fn one_line(value: &str) -> String {
    value.replace(['\r', '\n'], " ").trim().to_string()
}

fn quote(value: &str) -> String {
    let value = value.trim();
    if value.is_empty() {
        "No description was recorded.".to_string()
    } else {
        value.to_string()
    }
}

/// The audit line for a completed generation.
pub fn generated_event(submission: &Submission) -> TaskEvent {
    TaskEvent::SubmissionDocumentationGenerated {
        written: submission.written.clone(),
        preserved: submission.preserved.clone(),
    }
}

