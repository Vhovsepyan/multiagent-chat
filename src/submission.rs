    /// Required test 2 and 4: an incomplete run is documented as incomplete,
    /// and what is missing reaches the status and the next steps.
    #[test]
    fn an_incomplete_task_is_documented_honestly() {
        let root = project("incomplete");
        let mut task = finished_task("unused-secret-value");
        task.status = TaskStatus::Failed;
        task.error = Some("one or more verification commands failed".into());
        task.acceptance[1].status = CriterionStatus::Failed;
        task.acceptance[1]
            .blocking_findings
            .push("[blocker] AC-002: reminders never fire".into());
        let failed = vec![VerificationResult {
            command: "cargo test".into(),
            success: false,
            output: "1 failed".into(),
        }];

        generate(&task, &root, &failed);

        let readme = read(&root, "README.md");
        assert!(readme.contains("Task status: **failed**"), "{readme}");
        assert!(readme.contains("| `cargo test` | FAILED |"), "{readme}");
        assert!(readme.contains("Outstanding criteria: AC-002"), "{readme}");
        assert!(
            readme.contains("This project is **not** complete"),
            "{readme}"
        );
        assert!(readme.contains("`AC-002` is FAILED"), "{readme}");

        let next = read(&root, "docs/NEXT_STEPS.md");
        assert!(next.contains("## Required but incomplete"), "{next}");
        assert!(next.contains("`AC-002` [FAILED]"), "{next}");
        assert!(next.contains("reminders never fire"), "{next}");
        assert!(
            next.contains("Verification command `cargo test` failed"),
            "{next}"
        );
        // Optional work stays separate from what the specification required.
        let optional = next
            .split("## Optional future improvements")
            .nth(1)
            .unwrap();
        assert!(optional.contains("Mobile clients."), "{optional}");
        assert!(!optional.contains("AC-002"), "{optional}");
        fs::remove_dir_all(root).ok();
    }

